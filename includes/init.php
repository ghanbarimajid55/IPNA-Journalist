<?php

// Prevent direct access
if (basename($_SERVER['SCRIPT_FILENAME'] ?? '') === 'init.php') {
    http_response_code(403);
    exit('Direct access not permitted.');
}

// ── Secure session cookies (Phase 1) ──────────────────────────
// Applied before config.php's session_start() so every request inherits them.
$isHttps = (($_SERVER['HTTPS'] ?? '') !== '' && $_SERVER['HTTPS'] !== 'off')
    || (int)($_SERVER['SERVER_PORT'] ?? 80) === 443;
session_set_cookie_params([
    'lifetime' => 0,
    'path'     => '/',
    'httponly' => true,
    'secure'   => $isHttps,
    'samesite' => 'Lax',
]);

// Load core configuration (generated by the installer; absent on a fresh clone)
$configFile = BASE_PATH . '/config/config.php';
if (is_file($configFile)) {
    require_once $configFile;
}

// Check installation state.
// The installer creates /.installed after a successful installation.
// Do not use "non-empty database password" as an installation criterion,
// because XAMPP/MySQL commonly uses root with an empty password.
$isInstalled = false;

$installedMarker = BASE_PATH . '/.installed';
$dbConfigPath = BASE_PATH . '/config/database.php';

if (file_exists($installedMarker) && file_exists($dbConfigPath)) {
    $dbConfig = require $dbConfigPath;

    if (
        is_array($dbConfig)
        && !empty($dbConfig['host'])
        && !empty($dbConfig['dbname'])
        && !empty($dbConfig['username'])
    ) {
        $isInstalled = true;
    }
}

// If not installed, redirect to installer
if (!$isInstalled) {
    $requestUri = parse_url($_SERVER['REQUEST_URI'] ?? '', PHP_URL_PATH);
    $installPath = defined('BASE_URL') ? BASE_URL . '/install' : '/install';
    if (strpos($requestUri, $installPath) !== 0) {
        header('Location: ' . $installPath . '/');
        exit;
    }
}

// Load all includes
require_once BASE_PATH . '/includes/Database.php';
require_once BASE_PATH . '/includes/Helper.php';
require_once BASE_PATH . '/includes/Auth.php';
require_once BASE_PATH . '/includes/Middleware.php';

// ── Lightweight autoloader ────────────────────────────────────
// Maps flat class names to files, e.g.:
//   Admin_UserController -> controllers/Admin/UserController.php
//   AuthController       -> controllers/AuthController.php
//   User                 -> models/User.php
spl_autoload_register(function (string $class): void {
    $relative = str_replace(['\\', '_'], '/', $class);
    foreach (['/controllers/', '/models/'] as $dir) {
        $file = BASE_PATH . $dir . $relative . '.php';
        if (is_file($file)) {
            require_once $file;
            return;
        }
    }
});

// Global helper functions for views
function url(string $path = ''): string {
    return Helper::url($path);
}
function e(?string $value): string {
    return Helper::e($value);
}
function csrf_token(): string {
    return Auth::generateCsrfToken();
}
// Previous form value (no old-input store yet; returns the default)
function old(string $key, mixed $default = ''): mixed {
    return $_SESSION['old'][$key] ?? $default;
}
// Jalali month name for a month number 1..12
function jdate_month(int $month): string {
    static $months = [
        1 => 'فروردین', 2 => 'اردیبهشت', 3 => 'خرداد', 4 => 'تیر',
        5 => 'مرداد', 6 => 'شهریور', 7 => 'مهر', 8 => 'آبان',
        9 => 'آذر', 10 => 'دی', 11 => 'بهمن', 12 => 'اسفند',
    ];
    return $months[$month] ?? '';
}

// ── Global error handling (Phase 3) ───────────────────────────
// Uncaught exceptions/errors are logged to storage/logs and rendered
// as a clean 500 page. When APP_DEBUG is true, details are shown.
function pms_log_error(string $message, string $context = ''): void {
    $dir = BASE_PATH . '/storage/logs';
    if (!is_dir($dir)) {
        @mkdir($dir, 0775, true);
    }
    $line = sprintf("[%s] %s%s\n", date('Y-m-d H:i:s'), $message, $context !== '' ? ' | ' . $context : '');
    @file_put_contents($dir . '/app-' . date('Y-m-d') . '.log', $line, FILE_APPEND);
}

set_exception_handler(function (Throwable $e): void {
    $debug = defined('APP_DEBUG') && APP_DEBUG;
    pms_log_error(get_class($e) . ': ' . $e->getMessage(), $e->getFile() . ':' . $e->getLine());
    if (!headers_sent()) {
        http_response_code(500);
        header('Content-Type: text/html; charset=UTF-8');
    }
    if ($debug) {
        echo '<h1>500 — ' . e($e->getMessage()) . '</h1><pre>' . e($e->getTraceAsString()) . '</pre>';
    } else {
        echo '<h1>500 — خطای داخلی سرور</h1><p>یک خطای پیشبینی‌نشده رخ داده است. جزئیات در فایل لاگ ثبت شد.</p>';
    }
    exit;
});

set_error_handler(function (int $severity, string $message, string $file, int $line): bool {
    if (!(error_reporting() & $severity)) {
        return false;
    }
    pms_log_error('PHP[' . $severity . '] ' . $message, $file . ':' . $line);
    return true;
});

// Set timezone to Asia/Tehran
date_default_timezone_set('Asia/Tehran');

// Define today's Jalali date
if ($isInstalled) {
    $todayGregorian = date('Y-m-d');
    [$todayJy, $todayJm, $todayJd] = Helper::gregorianToJalali(
        (int) date('Y'),
        (int) date('n'),
        (int) date('j')
    );
    define('TODAY_JALALI', sprintf('%04d/%02d/%02d', $todayJy, $todayJm, $todayJd));
    define('TODAY_GREGORIAN', $todayGregorian);
}

// Initialize database connection
if ($isInstalled) {
    try {
        Database::getInstance();
    } catch (RuntimeException $e) {
        error_log('Database connection failed: ' . $e->getMessage());
        if (php_sapi_name() !== 'cli') {
            http_response_code(500);
            echo '<h1>Database Connection Error</h1><p>Please check your database configuration.</p>';
        }
        exit;
    }
}
